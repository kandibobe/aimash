"""A9: защита экспортов (.xlsx/.csv/Google Sheets) от формула-инъекции (CSV injection).

openpyxl/Google Sheets трактуют строку, начинающуюся с `= + - @` (и управляющих tab/CR), как
ФОРМУЛУ. В экспорт попадают неконтролируемые ботом строки: имена кампаний/групп/аккаунтов и тексты
ключей (из Google Ads по данным клиента). Строка вроде `=HYPERLINK("http://evil","click")` в имени
кампании стала бы кликабельной формулой в чужой таблице (утечка/фишинг при открытии отчёта).

Единый санитайзер: префикс `'` (апостроф) перед опасным ведущим символом — Excel/Sheets покажут
текст как есть, но НЕ выполнят как формулу. Числа/даты/None не трогаем (форматирование сохраняется)."""

from __future__ import annotations

# Ведущие символы, с которых Excel/Sheets начинают формулу (или ломают парсинг ячейки).
_DANGEROUS_LEADING = ("=", "+", "-", "@", "\t", "\r")


def safe_cell(value: object) -> object:
    """Обезвредить ОДНУ ячейку: если это строка с опасным ведущим символом — префикс апострофа.
    Не-строки (int/float/None/date) возвращаем как есть — формат числа/даты сохраняется."""
    if isinstance(value, str) and value[:1] in _DANGEROUS_LEADING:
        return "'" + value
    return value


def safe_row(row: object) -> list:
    """Обезвредить каждую ячейку строки-списка. Пустой/None → []."""
    return [safe_cell(v) for v in (row or [])]
