#!/bin/sh
# Entrypoint контейнера бота: применить миграции БД ДО старта, затем запустить переданную команду.
#
# Зачем: на Postgres (prod) истина схемы — Alembic. Раньше `alembic upgrade head` был ручным шагом
# (docs/DEPLOYMENT.md) — на свежем VPS/рестарте его легко забыть → схема дрейфует от моделей.
# Здесь миграции применяются автоматически при штатном старте бота. Если миграция падает —
# контейнер НЕ стартует (fail-fast: лучше не подняться, чем работать на рассинхронизированной БД).
#
# Миграции гоняем ТОЛЬКО когда команда == штатный запуск бота, чтобы не мешать
# `docker compose run --rm bot alembic ...` / `... bash` (там миграции ни к чему).
set -e

if [ "$1" = "python" ] && [ "$2" = "-m" ] && [ "$3" = "bot.main" ]; then
  echo "[entrypoint] alembic upgrade head…"
  alembic upgrade head
  echo "[entrypoint] миграции применены."
fi

exec "$@"
