"""BZ-1: аварийный рубильник мутаций — оперативный СТОП денежного пути без рестарта процесса.

Зачем отдельный модуль, когда есть замок аккаунта: до 2026-07-30 «выключить мутации» требовало
либо рестарта (settings — синглтон, снятый один раз на старте), либо `docker compose stop bot`
(глушит и чтение, и алерты). Хуже: пустой `GOOGLE_ADS_ALLOWED_CUSTOMER_IDS` в prod коэрцился в
«all» — попытка выключить очисткой env ОТКРЫВАЛА мутации (коэрция снята той же правкой).

Два НЕЗАВИСИМЫХ канала, оба проверяются на КАЖДОМ вызове (кэша нет намеренно):
  • env `DISABLE_ALL_MUTATIONS` — читается живьём из os.environ, МИМО settings-синглтона.
    Переживает пересоздание контейнера (env_file) — «устойчивый» стоп.
  • файл-флаг `settings.kill_switch_file` (дефолт `KILL_SWITCH`, путь относительно CWD процесса).
    В Compose это общий read-only mount `/run/aimash-safety/KILL_SWITCH`: root создаёт файл на
    хосте в `/opt/aimash/runtime/safety`, а bot/Hermes MCP и scheduler видят один рубильник.
    Он действует МГНОВЕННО, без рестарта, и переживает пересоздание контейнеров.

Семантика env — fail-closed (правило 10): рубильник ВЫКЛЮЧЕН только явно «выключенными»
значениями («», 0, false, no, off — регистронезависимо). Любое другое непустое значение,
включая опечатку («flase», «disable»), трактуется как ВКЛЮЧЁН: рубильник, который от опечатки
молча остаётся выключенным, — не рубильник.

Точки врезки — оба чокпойнта денежного пути (defense-in-depth, не дубль ради дубля):
`ads.client.ensure_allowed` (проверка №0 замка) и `ads.mutations._require_confirmation`
(ДО claim — отказ рубильника не сжигает одноразовое подтверждение). ЧТЕНИЕ не трогаем:
рубильник про деньги, отчёты и алерты продолжают работать.
"""

from __future__ import annotations

import os
from pathlib import Path

from core.config import settings

ENV_VAR = "DISABLE_ALL_MUTATIONS"

# Единственные значения env, при которых рубильник ВЫКЛЮЧЕН. Всё прочее = включён (fail-closed).
_OFF_VALUES = frozenset({"", "0", "false", "no", "off"})


class GateRefusal(PermissionError):
    """Отказ ПОЛИТИКИ до claim: рубильник (BZ-1) или исчерпанный кап (B1-4).

    Отличие от прочих PermissionError денежного пути — черновик ОСТАЁТСЯ валидным: причина
    отказа внешняя и временная (снимут рубильник / уедет 24-часовое окно капа), та же карточка
    исполнима повторным ✅. Обработчик подтверждения обязан НЕ жечь черновик (не record_failure),
    а вернуть его в pending. Остальные PermissionError (нет снимка, чужая операция, невалидный
    confirmation_id) — дефект самого черновика, для них сжигание корректно."""


def mutations_disabled() -> str | None:
    """Причина остановки мутаций, если рубильник включён; None — мутации разрешены.

    Порядок каналов не имеет значения (любой включённый — стоп); env первым лишь потому,
    что он дешевле обращения к ФС."""
    raw = os.environ.get(ENV_VAR, "")
    if raw.strip().lower() not in _OFF_VALUES:
        # Имя канала БЕЗ сырого значения: текст уходит пользователю в Telegram, а env-значение —
        # чужой ввод (правило 5: наружу только то, что написали мы сами).
        return f"env {ENV_VAR}"
    flag = (settings.kill_switch_file or "").strip()
    if flag:
        try:
            if Path(flag).exists():
                return f"файл-флаг {flag}"
        except OSError:
            # ФС не смогла ответить, существует ли флаг ⇒ считаем, что включён (правило 10):
            # «не смогли проверить рубильник» и «рубильник выключен» — разные утверждения.
            return f"файл-флаг {flag} (ФС недоступна для проверки)"
    return None


def ensure_mutations_enabled() -> None:
    """GateRefusal (подкласс PermissionError), если аварийный рубильник включён. Зовётся денежным
    путём (ensure_allowed, _require_confirmation) на каждой мутации; черновик при отказе жив."""
    reason = mutations_disabled()
    if reason is not None:
        raise GateRefusal(
            f"мутации остановлены аварийным рубильником ({reason}) — операция отклонена. "
            f"Снять: убрать {ENV_VAR} из окружения и удалить файл-флаг"
        )
